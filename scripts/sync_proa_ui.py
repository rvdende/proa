"""Mirror the public `@proa` UI registry (ui.proa.so) into `proa_ui/`.

Seeds are every component and block listed in the registry site's sitemap plus
the hidden `foundation` manifest; dependencies are followed transitively, so
items missing from the sitemap are still fetched. Every artifact is verified
against its manifest SHA-256 before anything on disk changes.

Only the Free tier is mirrored. `@proa-pro` items are authenticated and are
reported, never fetched.

Usage:
    python3 scripts/sync_proa_ui.py          # refresh proa_ui/
    python3 scripts/sync_proa_ui.py --check  # exit 1 if proa_ui/ has drifted
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import sys
import tempfile
import urllib.error
import urllib.request
from pathlib import Path, PurePosixPath
from urllib.parse import urljoin

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT = REPO_ROOT / "proa_ui"
SITE = "https://ui.proa.so"
MANIFEST_URL = SITE + "/r/{name}.json"
SITEMAP_URL = SITE + "/sitemap.xml"
ALIASES = {"@components": PurePosixPath("src/components"), "@assets": PurePosixPath("public")}
GENERATED = ("src", "public", "manifests")
SLUG = re.compile(r"^[a-z0-9][a-z0-9_-]*$")
SITEMAP_ITEM = re.compile(r"<loc>\s*https://ui\.proa\.so/(?:components|blocks)/([a-z0-9_-]+)(?:/[^<]*)?</loc>")
USER_AGENT = "proa-ui-mirror (+https://github.com/Proa-Labs/proa)"


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read()


def seed_slugs() -> list[str]:
    sitemap = fetch(SITEMAP_URL).decode()
    return sorted({"foundation", *SITEMAP_ITEM.findall(sitemap)})


def dependency_slug(dependency: str) -> tuple[str, str]:
    """Split `@registry/slug` or a bare slug into (registry, slug)."""
    if dependency.startswith("@"):
        registry, _, slug = dependency.partition("/")
        return registry, slug
    return "@proa", dependency


def target_path(target: str) -> PurePosixPath:
    alias, _, rest = target.partition("/")
    relative = PurePosixPath(rest)
    if alias not in ALIASES or relative.is_absolute() or ".." in relative.parts or not rest:
        raise ValueError(f"refusing unsafe artifact target {target!r}")
    return ALIASES[alias] / relative


def collect() -> tuple[dict[str, dict], dict[PurePosixPath, bytes], list[str]]:
    manifests: dict[str, dict] = {}
    files: dict[PurePosixPath, bytes] = {}
    skipped: list[str] = []
    queue = seed_slugs()
    while queue:
        slug = queue.pop()
        if slug in manifests:
            continue
        if not SLUG.match(slug):
            raise ValueError(f"invalid slug {slug!r}")
        url = MANIFEST_URL.format(name=slug)
        try:
            manifest = json.loads(fetch(url))
        except urllib.error.HTTPError as error:
            if error.code == 404:
                skipped.append(f"{slug} (404 on public registry)")
                continue
            raise
        if manifest.get("name") != slug or manifest.get("registry") != "@proa":
            raise ValueError(f"{url}: manifest does not describe @proa/{slug}")
        manifests[slug] = manifest
        print(f"  {manifest.get('kind', 'component'):9} {slug}", file=sys.stderr)

        for entry in manifest.get("files", []):
            path = target_path(entry["target"])
            data = fetch(urljoin(url, entry["source"]))
            digest = "sha256:" + hashlib.sha256(data).hexdigest()
            if digest != entry["sha256"]:
                raise ValueError(f"{slug}: {entry['source']} hash {digest} != {entry['sha256']}")
            if files.get(path, data) != data:
                raise ValueError(f"{slug}: {path} conflicts with another manifest's bytes")
            files[path] = data

        for dependency in manifest.get("dependencies", []):
            registry, dep = dependency_slug(dependency)
            if registry == "@proa":
                queue.append(dep)
            else:
                skipped.append(f"{dependency} (required by {slug}; not public)")
    return manifests, files, skipped


def render(manifests: dict[str, dict], files: dict[PurePosixPath, bytes]) -> dict[PurePosixPath, bytes]:
    tree = dict(files)
    modules: dict[PurePosixPath, set[str]] = {}
    for manifest in manifests.values():
        for block in manifest.get("rustModules", []):
            modules.setdefault(target_path(block["target"]), set()).update(block["modules"])
    for path, names in modules.items():
        lines = ["// Generated by scripts/sync_proa_ui.py from the @proa registry manifests.", ""]
        lines += [f"pub mod {name};" for name in sorted(names)]
        tree[path] = ("\n".join(lines) + "\n").encode()
    for slug, manifest in manifests.items():
        body = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
        tree[PurePosixPath("manifests") / f"{slug}.json"] = body.encode()
    return tree


def on_disk() -> dict[PurePosixPath, bytes]:
    tree = {}
    for top in GENERATED:
        root = OUT / top
        if root.exists():
            for path in root.rglob("*"):
                if path.is_file():
                    tree[PurePosixPath(path.relative_to(OUT).as_posix())] = path.read_bytes()
    return tree


def write(tree: dict[PurePosixPath, bytes]) -> None:
    OUT.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(dir=OUT, prefix=".sync-") as staging:
        staging_root = Path(staging)
        for path, data in tree.items():
            destination = staging_root / path
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(data)
        for top in GENERATED:
            shutil.rmtree(OUT / top, ignore_errors=True)
            if (staging_root / top).exists():
                (staging_root / top).rename(OUT / top)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify proa_ui/ matches the registry; no writes")
    args = parser.parse_args()

    print(f"Resolving {SITE} registry...", file=sys.stderr)
    manifests, files, skipped = collect()
    tree = render(manifests, files)
    for item in sorted(set(skipped)):
        print(f"skipped: {item}", file=sys.stderr)

    if args.check:
        current = on_disk()
        drift = sorted(str(p) for p in tree.keys() | current.keys() if tree.get(p) != current.get(p))
        for path in drift:
            print(f"drift: {path}", file=sys.stderr)
        return 1 if drift else 0

    write(tree)
    kinds = [m.get("kind", "component") for m in manifests.values()]
    print(
        f"Mirrored {kinds.count('component')} components and {kinds.count('block')} blocks "
        f"({len(tree)} files) into {OUT.relative_to(REPO_ROOT)}/",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
